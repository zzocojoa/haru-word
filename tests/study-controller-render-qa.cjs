const assert = require('node:assert/strict');
const fs = require('node:fs');
const { build } = require('esbuild');
const { launchBrowser, closeBrowser } = require('./qa/runtime.cjs');
const dir = 'work/draft-controller-tests';
fs.mkdirSync(dir, { recursive: true });
(async () => {
  await build({ entryPoints: ['tests/study-controller-harness.tsx'], outfile: dir + '/harness.js', bundle: true, format: 'iife', platform: 'browser', logLevel: 'silent', define: { 'process.env.NODE_ENV': '"development"' } });
  const browser = await launchBrowser();
  const page = await browser.newPage();
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  try {
    await page.setContent('<html><body><div id="root"></div></body></html>');
    await page.addScriptTag({ path: dir + '/harness.js' });
    await page.getByRole('textbox', { name: '답', exact: true }).fill('이전 문제의 답');
    await page.getByRole('button', { name: '공개', exact: true }).click();
    await page.getByRole('heading', { name: /공개됨/ }).waitFor();
    await page.evaluate(() => window.studyHarness.patch({ index: 1 }));
    await page.getByRole('heading', { name: /harness-next/ }).waitFor();
    const commits = await page.evaluate(() => window.studyHarness.trace.filter(t => t.id === 'harness-next'));
    fs.writeFileSync(dir + '/transition-commits.json', JSON.stringify(commits, null, 2));
    assert.ok(commits.length);
    assert.ok(commits.every(t => t.answer === '' && !t.hint && !t.revealed), 'a committed new question inherited the old answer/reveal state: ' + JSON.stringify(commits));
    checks.push('every committed new question owns its own answer, hint and reveal state');
    await page.getByRole('textbox', { name: '답', exact: true }).fill('작성 중 답');
    assert.equal(await page.evaluate(() => window.studyHarness.recovery().sessions['harness-session'].records['harness-next'].draft.answer), '작성 중 답');
    await page.evaluate(() => window.studyHarness.refresh());
    assert.equal(await page.getByRole('textbox', { name: '답', exact: true }).inputValue(), '작성 중 답');
    checks.push('same-question state refresh preserves typing');
    await page.evaluate(() => { window.studyHarness.trace.length = 0; window.studyHarness.patch({ stage: 'ko' }); });
    await page.getByRole('heading', { name: /harness-next ko/ }).waitFor();
    const direction = await page.evaluate(() => window.studyHarness.trace.filter(t => t.stage === 'ko'));
    assert.ok(direction.length && direction.every(t => !t.answer && !t.revealed && !t.hint));
    checks.push('direction changes do not publish the previous direction answer');
    await page.getByRole('textbox', { name: '답', exact: true }).fill('retry 이전 답');
    await page.evaluate(() => {
      window.studyHarness.trace.length = 0;
      window.studyHarness.patch({ retryMode: true, retry: [{ id: 'harness-next', direction: 'ko' }] });
    });
    await page.waitForFunction(() => window.studyHarness.controller.s.retryMode);
    assert.equal(await page.getByRole('textbox', { name: '답', exact: true }).inputValue(), '');
    assert.ok((await page.evaluate(() => window.studyHarness.trace)).every(t => !t.answer && !t.revealed));
    checks.push('delayed retries start from their own snapshot');
    await page.evaluate(() => {
      window.lateAnswer = window.studyHarness.controller.setAnswer;
      window.latePending = window.studyHarness.controller.setAiPending;
      window.studyHarness.patch({ stage: 'sentence', retryMode: false, retry: [] });
    });
    await page.getByRole('heading', { name: /sentence/ }).waitFor();
    await page.evaluate(() => window.studyHarness.patch({ stage: 'ko', retryMode: true, retry: [{ id: 'harness-next', direction: 'ko' }] }));
    await page.getByRole('heading', { name: /harness-next ko/ }).waitFor();
    await page.getByRole('textbox', { name: '답', exact: true }).fill('현재 답');
    await page.evaluate(() => window.studyHarness.controller.setAiPending(true));
    await page.waitForFunction(() => window.studyHarness.controller.aiPending);
    await page.evaluate(() => { window.lateAnswer('오래된 답'); window.latePending(false); });
    assert.equal(await page.getByRole('textbox', { name: '답', exact: true }).inputValue(), '현재 답');
    assert.equal(await page.evaluate(() => window.studyHarness.controller.aiPending), true);
    checks.push('late callbacks cannot alter a later visit to the same question or release its AI lock');
    await page.evaluate(() => window.studyHarness.patch({ stage: 'sentence', retryMode: false, retry: [] }));
    await page.getByRole('heading', { name: /sentence/ }).waitFor();
    await page.evaluate(() => { window.lateFeedback = window.studyHarness.controller.storeFeedback; window.studyHarness.patch({ index: 0 }); });
    await page.getByRole('heading', { name: /harness-word sentence/ }).waitFor();
    const accepted = await page.evaluate(() => window.lateFeedback({ original: 'My old sentence.', correctedSentence: 'My old sentence.', meaningUsage: 'appropriate', grammar: 'natural', explanation: '검사', model: 'gemini-3.1-flash-lite', createdAt: new Date().toISOString() }));
    assert.equal(accepted, false);
    checks.push('late AI feedback does not attach to a different current target');
    await page.evaluate(() => window.studyHarness.patch({ stage: 'learn', index: 0 }));
    await page.getByRole('heading', { name: /harness-word learn/ }).waitFor();
    await page.evaluate(() => {
      const c = window.studyHarness.controller;
      c.setMeaning(value => ' ' + value + ' ');
      c.setExpression(value => ' ' + value + ' ');
    });
    await page.waitForFunction(() => window.studyHarness.controller.expression === ' an example ');
    assert.equal(await page.evaluate(() => window.studyHarness.controller.expressionTranslation), '하나의 예');
    await page.evaluate(() => {
      const c = window.studyHarness.controller;
      c.setExpression('another');
      c.setExpression(value => value + ' example');
      c.setExpressionTranslation('또 다른 예');
    });
    await page.waitForFunction(() => window.studyHarness.controller.expressionTranslation === '또 다른 예');
    assert.equal(await page.evaluate(() => window.studyHarness.controller.expression), 'another example');
    await page.evaluate(() => window.studyHarness.controller.setMeaning('다른 뜻'));
    await page.waitForFunction(() => window.studyHarness.controller.meaning === '다른 뜻');
    assert.equal(await page.evaluate(() => window.studyHarness.controller.expressionTranslation), '');
    checks.push('batched functional phrase edits use current values, preserve whitespace-only edits and clear changed meanings');
    await page.evaluate(() => {
      window.lateExpression = window.studyHarness.controller.setExpression;
      window.lateGloss = window.studyHarness.controller.setExpressionTranslation;
      window.studyHarness.patch({ index: 1 });
    });
    await page.getByRole('heading', { name: /harness-next learn/ }).waitFor();
    await page.evaluate(() => window.studyHarness.patch({ index: 0 }));
    await page.getByRole('heading', { name: /harness-word learn/ }).waitFor();
    await page.evaluate(() => { window.lateExpression('stale phrase'); window.lateGloss('오래된 해석'); });
    assert.deepEqual(await page.evaluate(() => {
      const c = window.studyHarness.controller;
      return [c.meaning, c.expression, c.expressionTranslation];
    }), ['예', 'an example', '하나의 예']);
    checks.push('phrase fields restore together and stale setters cannot change a later visit to the same learning card');
    await page.evaluate(() => window.studyHarness.controller.setExpression('latest recovery phrase'));
    await page.waitForFunction(() => window.studyHarness.controller.expression === 'latest recovery phrase');
    assert.equal(await page.evaluate(() => window.studyHarness.recovery().sessions['harness-session'].records['harness-word'].material.expression), 'latest recovery phrase');
    await page.evaluate(() => window.studyHarness.unmount());
    assert.equal(await page.evaluate(() => window.studyHarness.recovery().sessions['harness-session'].records['harness-word'].material.expression), 'an example');
    checks.push('StrictMode recovery captures latest local inputs, ignores stale setters, and unregisters on unmount');
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, checks, errors }));
  } finally { await closeBrowser(browser); }
})().catch(e => { console.error(e); process.exitCode = 1; });
