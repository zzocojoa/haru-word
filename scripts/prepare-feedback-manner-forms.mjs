import {readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const words=JSON.parse(await readFile(resolve(root,'data/words.json'),'utf8'));
// Productive -ful/-less adjective families only. The curriculum supplies POS;
// noun suffixes and arbitrary -ly derivations are not thereby authorized.
const bases=[...new Set(words.filter(w=>w.pos==='adj.'&&/^[a-z]+(?:ful|less)$/.test(w.word)).map(w=>w.word))].sort();
const body='// Generated by node scripts/prepare-feedback-manner-forms.mjs from data/words.json.\n// POS-bounded productive spelling families, not a general semantic-equivalence test.\nexport const PRODUCTIVE_MANNER_ADJECTIVES = '+JSON.stringify(bases)+' as const;\n';
const target=resolve(root,'lib/feedback-manner-adjectives.ts');
if(process.argv.includes('--check')){
 if(await readFile(target,'utf8')!==body)throw Error('Feedback morphology index is stale; regenerate from the curriculum.');
}else await writeFile(target,body);
console.log(JSON.stringify({productiveAdjectives:bases.length,checked:process.argv.includes('--check')}));
